def _scope(model, dimension):
    from app.rag.indexing import EmbeddingScope

    return EmbeddingScope(model, dimension)


def _registry(tmp_path, *, model=MODEL_A, dimension=DIM_WIDE):
    from app.rag.indexing import IndexRegistry

    return IndexRegistry(tmp_path / "indexes.json", scope=_scope(model, dimension))


def _load_legacy(tmp_path, registry):
    """Point a registry at the baseline file and re-read it, the way the field would."""
    path = tmp_path / "legacy-indexes.json"
    path.write_text(json.dumps(LEGACY_METADATA), encoding="utf-8")
    registry.metadata_path = path
    registry._load()
    return path


def _version(registry, *, index_id=INDEX, source="policy.txt|v1", chunks=3, checksum="a" * 64):
    return registry.create_version(
        index_id=index_id,
        source_version_id=source,
        backend="chroma",
        chunk_count=chunks,
        checksum=checksum,
    )

# ------------------------------------------------- 1. the version carries the profile
def test_a_version_records_which_model_and_width_produced_it(tmp_path):
    registry = _registry(tmp_path, model=MODEL_B, dimension=DIM_NARROW)
    version = _version(registry)
    registry.publish(version.index_version_id)

    assert (version.embedding_model, version.dimension) == (MODEL_B, DIM_NARROW)
    assert version.scope == _scope(MODEL_B, DIM_NARROW)

    reopened = _registry(tmp_path, model=MODEL_B, dimension=DIM_NARROW)
    persisted = reopened.current(INDEX)
    assert (persisted.embedding_model, persisted.dimension) == (MODEL_B, DIM_NARROW)


def test_a_version_that_names_no_profile_inherits_the_configured_one(tmp_path):
    registry = _registry(tmp_path, model=MODEL_A, dimension=DIM_WIDE)
    version = _version(registry)

    assert version.embedding_model == MODEL_A
    assert version.dimension == DIM_WIDE


def test_naming_only_the_width_still_keeps_the_configured_model(tmp_path):
    from app.rag.indexing import IndexScopeError

    # Naming one axis must not be read as "don't care about the other": a query that only
    # knows its width still cannot borrow a different model's vectors.
    registry = _registry(tmp_path, model=MODEL_A, dimension=DIM_WIDE)
    version = registry.create_version(
        index_id=INDEX,
        source_version_id="policy.txt|v1",
        backend="chroma",
        chunk_count=1,
        checksum="a" * 64,
        dimension=DIM_NARROW,
    )

    assert version.dimension == DIM_NARROW
    assert version.embedding_model == MODEL_A
    # Never published, so no width may search it.
    assert registry.queryable_version_ids(dimension=DIM_WIDE) == frozenset()
    assert registry.queryable_version_ids(dimension=DIM_NARROW) == frozenset()
    # It cannot be published under the configured 768 either: half a match is not a match.
    with pytest.raises(IndexScopeError):
        registry.publish(version.index_version_id)

    registry._fixed_scope = _scope(MODEL_A, DIM_NARROW)
    registry.publish(version.index_version_id)
    assert registry.queryable_version_ids(dimension=DIM_NARROW) == frozenset({version.index_version_id})
    assert registry.queryable_version_ids(dimension=DIM_WIDE) == frozenset()


