# --------------------------------- the profile is read live, not frozen at import time
def test_editing_the_embedder_constant_moves_the_configured_profile(tmp_path, monkeypatch):
    import app.rag.retriever as retriever_module
    from app.rag.indexing import IndexRegistry, configured_embedding_scope

    monkeypatch.delenv("EMBEDDING_MODEL", raising=False)
    original = retriever_module.EMBED_MODEL
    assert configured_embedding_scope().embedding_model == original

    registry = IndexRegistry(tmp_path / "indexes.json")
    before = _version(registry, chunks=1)
    registry.publish(before.index_version_id)
    assert before.embedding_model == original

    monkeypatch.setattr(retriever_module, "EMBED_MODEL", "upgraded-embed-v2")
    # No restart, no re-import: the same live registry now means a different profile.
    assert registry.scope.embedding_model == "upgraded-embed-v2"

    from app.rag.indexing import CODE_MODEL_DRIFT, IndexScopeError

    with pytest.raises(IndexScopeError) as refused:
        registry.validate(before.index_version_id)
    assert refused.value.code == "embedding_scope_mismatch"
    assert CODE_MODEL_DRIFT in refused.value.codes


