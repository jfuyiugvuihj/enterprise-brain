# ------------------------------- 2. either axis changing cannot reuse the old version
def test_a_dimension_change_cannot_revalidate_or_republish_the_old_version(tmp_path):
    from app.rag.indexing import CODE_DIMENSION_DRIFT, CODE_SCOPE_MISMATCH, IndexScopeError

    registry = _registry(tmp_path, dimension=DIM_NARROW)
    old = _version(registry)
    registry.publish(old.index_version_id)

    # The operator changes the embedder. Nothing restarts: the registry reads the profile on
    # demand, so the change bites at the next decision rather than at the next deploy.
    registry._fixed_scope = _scope(MODEL_A, DIM_WIDE)

    with pytest.raises(IndexScopeError) as refused:
        registry.validate(old.index_version_id)
    assert refused.value.code == CODE_SCOPE_MISMATCH
    assert CODE_DIMENSION_DRIFT in refused.value.codes
    with pytest.raises(IndexScopeError):
        registry.publish(old.index_version_id)

    # The only way forward is a new version, and producing one does not destroy the old.
    rebuilt = _version(registry, checksum="a" * 64)
    registry.publish(rebuilt.index_version_id)
    assert rebuilt.index_version_id != old.index_version_id
    assert registry.current(INDEX).index_version_id == rebuilt.index_version_id
    assert registry.current(INDEX).dimension == DIM_WIDE
    assert registry._versions[old.index_version_id].status == "superseded"


def test_a_model_change_with_an_identical_payload_still_lands_on_a_new_version(tmp_path):
    """Same document, same chunks, same checksum -- only the embedder moved.

    This is the case a content hash cannot see: nothing about the text changed, so a registry
    that did not bind the profile would keep pointing at vectors another model computed, and
    every retrieval number would quietly describe a different library.
    """
    registry = _registry(tmp_path, model=MODEL_A)
    old = _version(registry)
    registry.publish(old.index_version_id)

    registry._fixed_scope = _scope(MODEL_B, DIM_WIDE)
    rebuilt = _version(registry)
    registry.publish(rebuilt.index_version_id)

    assert rebuilt.checksum == old.checksum
    assert rebuilt.index_version_id != old.index_version_id
    assert rebuilt.embedding_model == MODEL_B
    assert registry.queryable_version_ids(index_id=INDEX) == frozenset({rebuilt.index_version_id})
    assert old.index_version_id not in registry.queryable_version_ids()
    assert registry._versions[old.index_version_id].status == "superseded"

# ------------------------------------------- 3. two profiles never answer one query
def test_a_current_version_is_refused_when_the_query_uses_another_width(tmp_path):
    from app.rag.indexing import CODE_SCOPE_MISMATCH, IndexScopeError

    registry = _registry(tmp_path, dimension=DIM_WIDE)
    old = _version(registry, source="policy.txt|v1")
    registry.publish(old.index_version_id)

    registry._fixed_scope = _scope(MODEL_A, DIM_NARROW)
    narrow = _version(registry, source="policy.txt|v2")
    registry.publish(narrow.index_version_id)

    assert registry.queryable_version_ids(dimension=DIM_NARROW) == frozenset({narrow.index_version_id})
    assert registry.queryable_version_ids(dimension=DIM_WIDE) == frozenset({old.index_version_id})
    with pytest.raises(IndexScopeError) as refused:
        registry.queryable_version(INDEX, dimension=DIM_WIDE)
    assert refused.value.code == CODE_SCOPE_MISMATCH
    # The unscoped bookkeeping read still answers, so reporting never becomes an outage.
    assert registry.current(INDEX).index_version_id == narrow.index_version_id


def test_cross_dimension_hits_are_dropped_rather_than_ranked(tmp_path):
    """Zero hits from the other profile, measured over the records themselves."""
    from app.rag.indexing import retain_queryable

    registry = _registry(tmp_path, dimension=DIM_WIDE)
    old = _version(registry, source="policy.txt|v1")
    registry.publish(old.index_version_id)
    registry._fixed_scope = _scope(MODEL_A, DIM_NARROW)
    current = _version(registry, source="policy.txt|v2")
    registry.publish(current.index_version_id)

    hits = [
        {"index_version_id": old.index_version_id, "content": "stale, other width"},
        {"index_version_id": current.index_version_id, "content": "right width"},
        {"content": "a hit that names no version at all"},
    ]

    kept = retain_queryable(registry, hits, dimension=DIM_NARROW)
    assert [row["content"] for row in kept] == ["right width"]
    assert sum(1 for row in kept if row["index_version_id"] == old.index_version_id) == 0

    # Ask for a width nothing publishes at and the answer is empty, not the old vectors:
    # "there is nothing under that profile" is the only honest reply.
    assert retain_queryable(registry, hits, dimension=1024) == []


def test_rollback_cannot_switch_an_index_back_to_another_widths_version(tmp_path):
    from app.rag.indexing import CODE_SCOPE_MISMATCH, IndexScopeError

    registry = _registry(tmp_path, dimension=DIM_NARROW)
    narrow = _version(registry, source="policy.txt|v1")
    registry.publish(narrow.index_version_id)
    registry._fixed_scope = _scope(MODEL_A, DIM_WIDE)
    wide = _version(registry, source="policy.txt|v2")
    registry.publish(wide.index_version_id)

    with pytest.raises(IndexScopeError) as refused:
        registry.rollback(INDEX, narrow.index_version_id)
    assert refused.value.code == CODE_SCOPE_MISMATCH
    assert registry.current(INDEX).index_version_id == wide.index_version_id

    # Rolling the *configuration* back first makes it a like-for-like restore again.
    registry._fixed_scope = _scope(MODEL_A, DIM_NARROW)
    restored = registry.rollback(INDEX, narrow.index_version_id)
    assert restored.index_version_id == narrow.index_version_id


def test_discard_refuses_to_erase_the_other_profiles_rollback_target(tmp_path):
    from app.rag.indexing import CODE_SCOPE_MISMATCH, IndexScopeError

    registry = _registry(tmp_path, dimension=DIM_NARROW)
    narrow = _version(registry, source="policy.txt|v1")
    registry.publish(narrow.index_version_id)
    registry._fixed_scope = _scope(MODEL_A, DIM_WIDE)

