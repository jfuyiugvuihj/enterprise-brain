"""R22 (docs/handoff/2026-09-15-backend-followup-requests.md section 18, restated in section 22).

An index version is the unit an embedding profile is bound to: ``embedding_model`` plus
``dimension``. These tests pin what makes the binding real rather than decorative -- a version
carries both values, either one changing cannot reuse the old version, two profiles never serve
the same query, and a record written before the binding existed loads as *unknown* instead of
quietly claiming whatever model is configured now.
"""
