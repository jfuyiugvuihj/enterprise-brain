# ------------------------------------------------------- drift, for a health check to read
def test_drift_names_the_axis_that_moved_and_the_versions_affected(tmp_path):
    registry = _registry(tmp_path, model=MODEL_A, dimension=DIM_WIDE)
    clean = _version(registry, source="policy.txt|v1")
    registry.publish(clean.index_version_id)

    settled = registry.embedding_drift()
    assert settled.drifted is False
    assert settled.codes == ()
    assert settled.checked == 1

    registry._fixed_scope = _scope(MODEL_B, DIM_WIDE)
    drifted = registry.embedding_drift()
    assert drifted.drifted is True
    assert drifted.codes == ("embedding_model_drift",)
    assert drifted.affected_index_version_ids == (clean.index_version_id,)
    assert drifted.configured == _scope(MODEL_B, DIM_WIDE)
    assert drifted.as_dict()["codes"] == ["embedding_model_drift"]

    registry._fixed_scope = _scope(MODEL_B, DIM_NARROW)
    both = registry.embedding_drift()
    assert set(both.codes) == {"embedding_model_drift", "embedding_dimension_drift"}

    _load_legacy(tmp_path, registry)
    unknown = registry.embedding_drift()
    assert "embedding_scope_unknown" in unknown.codes
    assert set(unknown.unknown_index_version_ids) == set(LEGACY_METADATA["current"].values())


def test_the_publisher_binds_every_publication_it_makes(tmp_path):
    from app.rag.indexing import DocumentIndexPublication, IndexPublisher

    registry = _registry(tmp_path, model=MODEL_A, dimension=DIM_WIDE)
    publisher = IndexPublisher(registry, store=None)
    outcome = publisher.publish(
        DocumentIndexPublication(filename="policy.txt", version=1, chunks=("one", "two"))
    )

    assert outcome.embedding_model == MODEL_A
    assert outcome.dimension == DIM_WIDE
    assert outcome.as_dict()["dimension"] == DIM_WIDE
    assert registry.current(INDEX).scope == _scope(MODEL_A, DIM_WIDE)

    # Moving the config half-way through cannot relabel a publication: create, validate and
    # publish all use the one scope the publisher resolved at the start.
    registry._fixed_scope = _scope(MODEL_B, DIM_WIDE)
    second = publisher.publish(
        DocumentIndexPublication(filename="policy.txt", version=2, chunks=("one", "two"))
    )
    assert second.embedding_model == MODEL_B
    assert second.previous_index_version_id == outcome.index_version_id


def test_an_aborted_publication_forgets_its_own_version_even_over_a_legacy_current(tmp_path):
    """A scope gate must not turn a rollback refusal into a stranded version.

    Before this change the two undo steps shared one try, so a refused rollback skipped the
    discard and left a version in the registry that nobody had published.
    """
    from app.rag.indexing import DocumentIndexPublication, IndexPublisher, IndexRegistry

    registry = _registry(tmp_path, model=MODEL_A, dimension=DIM_WIDE)
    _load_legacy(tmp_path, registry)
    legacy_id = LEGACY_METADATA["current"][INDEX]
    publisher = IndexPublisher(registry, store=None)

    def refuse(index_version_id):
        raise RuntimeError("the index metadata file is read only")

    registry.publish = refuse
    with pytest.raises(Exception):
        publisher.publish(
            DocumentIndexPublication(filename="policy.txt", version=2, chunks=("one", "two"))
        )

    assert legacy_id in registry._versions
    assert len(registry._versions) == 2
    assert registry.current(INDEX).index_version_id == legacy_id


class _RecordingConnection:
    def __init__(self):
        self.calls = []

    def execute(self, sql, params=()):
        self.calls.append((" ".join(str(sql).split()), params))
        return self

    def fetchone(self):
        return None


